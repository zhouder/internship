// Runs inside the caller's transaction on SQLite and PostgreSQL. It adds only
// missing content, leaves stock/orders untouched, and never replaces custom art.
export async function enrichCatalog(db) {
  const get = (sql, ...args) => db.prepare(sql).get(...args);
  const run = (sql, ...args) => db.prepare(sql).run(...args);
  const key = "catalog-content-2026-v2";
  if (await get("SELECT value FROM settings WHERE key=?", key)) return;
  const now = "2026-11-10T04:00:00.000Z";
  const old = await db.prepare("SELECT id,category,image FROM resources").all();
  for (const resource of old) {
    if (
      ["/images/performance.png", "/images/venue.png"].includes(resource.image)
    )
      await run(
        "UPDATE resources SET image=? WHERE id=?",
        categoryImages[resource.category],
        resource.id,
      );
  }
  const added = [];
  for (const resource of catalogResources) {
    if (await get("SELECT id FROM resources WHERE name=?", resource.name))
      continue;
    await run(
      "INSERT INTO resources(name,category,city,price,unit,description,image,capacity,stock,tags,meta,owner_id,views,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
      resource.name,
      resource.category,
      resource.city,
      resource.price,
      resource.unit,
      resource.description,
      resource.image,
      resource.capacity,
      resource.stock,
      JSON.stringify(resource.tags),
      JSON.stringify(resource.meta),
      3,
      80 + added.length * 23,
      now,
    );
    const row = await get(
      "SELECT id FROM resources WHERE name=?",
      resource.name,
    );
    added.push({ ...resource, id: row.id });
  }
  for (const [title, category, budget, city, description] of extraDemands) {
    if (!(await get("SELECT id FROM demands WHERE title=?", title)))
      await run(
        "INSERT INTO demands(user_id,title,category,budget,city,description,status,created_at) VALUES(?,?,?,?,?,?,?,?)",
        3,
        title,
        category,
        budget,
        city,
        description,
        "approved",
        now,
      );
  }
  const reviews = [
    "介绍清楚，沟通时对活动流程给出了很实用的建议。",
    "文化特色鲜明，适合朋友结伴体验，期待更多周末场次。",
    "场景和内容很有广西特色，计划再带家人一起了解。",
  ];
  for (const [index, resource] of added.slice(0, 18).entries())
    await run(
      "INSERT INTO comments(user_id,resource_id,rating,content,status,created_at) VALUES(?,?,?,?,?,?)",
      4 + (index % 12),
      resource.id,
      index % 4 === 0 ? 4 : 5,
      reviews[index % reviews.length],
      "approved",
      now,
    );
  await run(
    "INSERT INTO settings(key,value) VALUES(?,?)",
    key,
    JSON.stringify({ resources: added.length, version: 2 }),
  );
}
