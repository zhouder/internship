import { AsyncLocalStorage } from "node:async_hooks";
import pg from "pg";
import { attachDatabasePool } from "@vercel/functions";
import { schema } from "./schema.mjs";
import { demoStatements } from "./demo-data.mjs";

// PostgreSQL aggregates return int8/numeric strings; the demo API uses numbers.
pg.types.setTypeParser(20, Number);
pg.types.setTypeParser(1700, Number);
const writeLock = 71426011;

export function postgresSql(sql) {
  let index = 0;
  return sql.replace(/'(?:''|[^'])*'|\?/g, (token) =>
    token === "?" ? `$${++index}` : token,
  );
}

export async function openPostgresStore(
  connectionString,
  { poolOptions = {} } = {},
) {
  if (!connectionString) throw new Error("DATABASE_URL is required");
  const connection = new URL(connectionString);
  if (connection.searchParams.get("sslmode") === "require")
    connection.searchParams.set("sslmode", "verify-full");
  const pool = new pg.Pool({
    connectionString: connection.toString(),
    max: 3,
    idleTimeoutMillis: 5000,
    connectionTimeoutMillis: 15000,
    ...poolOptions,
  });
  if (process.env.VERCEL) attachDatabasePool(pool);
  pool.on("error", (error) =>
    console.error("Database pool error", { code: error.code }),
  );
  const context = new AsyncLocalStorage();
  const execute = (sql, params = []) =>
    (context.getStore() || pool).query(postgresSql(sql), params);

  try {
    const client = await pool.connect();
    try {
      await client.query("BEGIN");
      await client.query("SELECT pg_advisory_xact_lock($1)", [writeLock]);
      await client.query(
        schema.replaceAll(
          "id INTEGER PRIMARY KEY",
          "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        ),
      );
      await client.query(
        "ALTER TABLE comments ADD COLUMN IF NOT EXISTS dimensions TEXT NOT NULL DEFAULT '{}'",
      );
      if (!(await client.query("SELECT COUNT(*) AS n FROM users")).rows[0].n) {
        // Batch adjacent inserts to keep first-time setup fast over the network.
        const groups = [];
        for (const [sql, params] of demoStatements()) {
          const last = groups.at(-1);
          if (last?.sql === sql) last.rows.push(params);
          else groups.push({ sql, rows: [params] });
        }
        for (const { sql, rows } of groups) {
          const [, prefix, values] = sql.match(
            /^(.*\bVALUES)\(([^()]*)\)\s*$/i,
          );
          const batch = `${prefix} ${rows.map(() => `(${values})`).join(",")}`;
          await client.query(postgresSql(batch), rows.flat());
        }
      }
      await client.query("COMMIT");
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally {
      client.release();
    }
  } catch (error) {
    await pool.end();
    throw error;
  }

  return {
    dialect: "postgres",
    prepare(sql) {
      return {
        all: async (...params) => (await execute(sql, params)).rows,
        get: async (...params) => (await execute(sql, params)).rows[0],
        run: async (...params) => {
          const insert =
            /^\s*INSERT\s+INTO\s+(users|resources|orders|demands|comments|messages|events|audit_logs)\b/i.test(
              sql,
            );
          const result = await execute(
            insert ? `${sql} RETURNING id` : sql,
            params,
          );
          return {
            changes: result.rowCount,
            lastInsertRowid: result.rows[0]?.id,
          };
        },
      };
    },
    close: () => pool.end(),
    async request(fn, { write, success }) {
      const client = await pool.connect();
      try {
        await client.query(
          write ? "BEGIN" : "BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY",
        );
        if (write) {
          // Small shared demo: serialize writes across all Vercel instances.
          // The lock is held before reading order state or checking availability.
          await client.query("SELECT pg_advisory_xact_lock($1)", [writeLock]);
        }
        const result = await context.run(client, fn);
        await client.query(success() ? "COMMIT" : "ROLLBACK");
        return result;
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    },
  };
}
