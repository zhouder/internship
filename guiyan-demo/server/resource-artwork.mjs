export async function enrichResourceArtwork(db) {
  const get = (sql, ...args) => db.prepare(sql).get(...args);
  const run = (sql, ...args) => db.prepare(sql).run(...args);
  const key = "resource-artwork-2026-v3";
  if (await get("SELECT value FROM settings WHERE key=?", key)) return;
  const resources = await db
    .prepare("SELECT id,name,image FROM resources")
    .all();
  let updated = 0;
  for (const resource of resources) {
    const image =
      additionalResourceArtwork.find(
        (item) =>
          item.resourceId === resource.id && item.name === resource.name,
      )?.image || byName.get(resource.name);
    if (
      image &&
      image !== resource.image &&
      legacyArtwork.has(resource.image)
    ) {
      await run("UPDATE resources SET image=? WHERE id=?", image, resource.id);
      updated++;
    }
  }
  await run(
    "INSERT INTO settings(key,value) VALUES(?,?)",
    key,
    JSON.stringify({ version: 3, updated }),
  );
}
