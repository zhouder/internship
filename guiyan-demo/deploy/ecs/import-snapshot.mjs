// One-time migration into an EMPTY PostgreSQL database; JSON is read from stdin.
// Source sessions are deliberately omitted so users log in again after migration.
import pg from "pg";
import assert from "node:assert/strict";
import { schema } from "../../server/schema.mjs";

const tables = [
  "users", "resources", "orders", "demands", "comments", "messages",
  "favorites", "events", "audit_logs", "settings",
];
const identifier = (name) => {
  assert.match(name, /^[a-z_]+$/);
  return `"${name}"`;
};
const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
let connected = false;
try {
  let input = "";
  for await (const chunk of process.stdin) {
    input += chunk;
    assert.ok(Buffer.byteLength(input) < 20_000_000, "Snapshot too large");
  }
  const snapshot = JSON.parse(input);
  assert.equal(snapshot.format, "guiyan-postgres-v1");
  assert.deepEqual(Object.keys(snapshot.tables), tables);
  await client.connect();
  connected = true;
  await client.query("BEGIN");
  await client.query("SELECT pg_advisory_xact_lock($1)", [71426011]);
  await client.query(schema.replaceAll(
    "id INTEGER PRIMARY KEY",
    "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  ));
  await client.query("ALTER TABLE comments ADD COLUMN IF NOT EXISTS dimensions TEXT NOT NULL DEFAULT '{}'");
  for (const table of [...tables, "sessions"]) {
    const result = await client.query(`SELECT COUNT(*)::int AS n FROM ${identifier(table)}`);
    assert.equal(result.rows[0].n, 0, `Refusing to replace existing data in ${table}`);
  }
  const counts = {};
  for (const table of tables) {
    const rows = snapshot.tables[table];
    assert.ok(Array.isArray(rows));
    if (rows.length) {
      const columns = Object.keys(rows[0]);
      const actual = await client.query(
        "SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=$1",
        [table],
      );
      assert.deepEqual([...columns].sort(), actual.rows.map(r => r.column_name).sort());
      for (const row of rows) {
        assert.deepEqual(Object.keys(row), columns);
        await client.query(
          `INSERT INTO ${identifier(table)} (${columns.map(identifier).join(",")}) VALUES (${columns.map((_, i) => `$${i + 1}`).join(",")})`,
          columns.map(name => row[name]),
        );
      }
      if (columns.includes("id")) {
        await client.query(
          `SELECT setval(pg_get_serial_sequence($1,'id'), COALESCE(MAX(id),1), MAX(id) IS NOT NULL) FROM ${identifier(table)}`,
          [table],
        );
      }
    }
    const result = await client.query(`SELECT COUNT(*)::int AS n FROM ${identifier(table)}`);
    assert.equal(result.rows[0].n, rows.length);
    counts[table] = rows.length;
  }
  await client.query("COMMIT");
  console.log(JSON.stringify({ imported: true, exportedAt: snapshot.exportedAt, counts, sessions: 0 }));
} catch (error) {
  if (connected) await client.query("ROLLBACK").catch(() => {});
  console.error(JSON.stringify({ imported: false, code: error.code || error.name }));
  process.exitCode = 1;
} finally {
  await client.end().catch(() => {});
}
